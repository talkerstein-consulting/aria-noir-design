/**
 * Square card photography for the colourway wall, and its manifest.
 *
 * Run: node scripts/build-colourway-cards.mjs
 *
 * ---- Why a second photograph rather than a crop ----
 *
 * The colourway shoot is wide — the frame on a sill, the room behind it —
 * and the card is square. Cropping one to the other throws away nearly half
 * the width, and what it throws away is the TEMPLES: the frame is the widest
 * thing in the picture, so it is the first thing a square crop cuts. No
 * `object-position` fixes that. A focal point can only choose WHICH temple
 * goes off the edge.
 *
 * So the square is extended rather than cropped. Each sill photograph was
 * outpainted to 1:1 with Higgsfield (the room continued above and below,
 * nothing inside the original frame touched) and saved beside it as
 * `x-square.webp`. This script only resizes and re-encodes that for the
 * card. A sill with no square is an error, not a fallback: the blurred
 * letterbox render this script used to make is gone and must not come back.
 *
 * ---- One render per colourway: the wall does not swap ----
 *
 * The house cards swap to a second photograph under the pointer. The wall
 * does not, and should not: every card on it is the same composition in a
 * different colour, so swapping the photograph moves the room, the light
 * and the angle at the exact moment the reader is comparing colours. It
 * zooms instead — the same gesture at lower volume, and the only thing
 * that changes is how close you are to the acetate.
 *
 * ---- The manifest is generated, like the catalogue ----
 *
 * Deriving `x-sill.webp` → `x-card.webp` by string at render time would
 * invent a path for a colourway that was never shot. This writes down what
 * actually came out of the render instead, and the wall reads that.
 */
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const PUB = path.join(process.cwd(), "public");
const SIZE = 1600;
/** Houses whose run has been shot on the sill. */
const HOUSES = ["ahava", "arca-ii", "matriarca", "monarca", "patriarca"];

/* A colourway shot for the storefront but never put on the sill does NOT
   get a card. MATRIARCA's Black Wood is the only one today: it was briefly
   built from its numbered set, which put a frame photographed in another
   session on a wall whose whole premise is one composition across a run.
   It comes off the wall instead — see the filter in shop/colourway-cards. */

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");

/** The outpainted square, resized for the card. */
async function fromSquare(srcPath, outPath) {
  await sharp(fs.readFileSync(srcPath))
    .resize(SIZE, SIZE, { fit: "cover" })
    .webp({ quality: 88 })
    .toFile(outPath);
}

const manifest = {};
let made = 0;

for (const house of HOUSES) {
  const dir = path.join(PUB, "images", house, "variants");
  if (!fs.existsSync(dir)) continue;
  const files = fs.readdirSync(dir);
  const rows = {};

  /* The sill shoot and nothing else. */
  for (const baseSrc of files.filter((f) => f.endsWith("-sill.webp"))) {
    const key = baseSrc.replace(/-sill\.webp$/, "");
    const out = path.join(dir, `${key}-card.webp`);
    const sq = path.join(dir, `${key}-square.webp`);
    if (!fs.existsSync(sq)) {
      throw new Error(`${house}/${key}: no ${key}-square.webp. Outpaint the sill first; the card is never a blurred crop.`);
    }
    await fromSquare(sq, out);
    made++;

    rows[key] = { image: `/images/${house}/variants/${key}-card.webp` };
  }
  if (Object.keys(rows).length) manifest[house] = rows;
}

/* Keyed by the SLUG of the colourway name, not the name itself: the names
   carry spaces and case that the files do not, and the wall already has the
   name in hand to slugify. */
const body = Object.entries(manifest)
  .map(([house, rows]) => {
    const inner = Object.entries(rows)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([k, v]) => `    "${k}": { image: "${v.image}" },`)
      .join("\n");
    return `  "${house}": {\n${inner}\n  },`;
  })
  .join("\n");

fs.writeFileSync(
  path.join(process.cwd(), "src/lib/colourway-cards.generated.ts"),
  `/**
 * GENERATED by scripts/build-colourway-cards.mjs — do not edit by hand.
 *
 * The square card renders for the colourway wall: the whole 16:9 sill
 * fitted into a square so the temples are not cropped. One per colourway —
 * the wall zooms on hover rather than swapping the photograph. See the
 * script's header.
 *
 * Keyed by house slug, then by the SLUG of the colourway name.
 */

export type ColourwayCardArt = {
  image: string;
};

export const COLOURWAY_CARD_ART: Record<
  string,
  Record<string, ColourwayCardArt>
> = {
${body}
};

/** The slug the map is keyed by. Matches the filenames on disk. */
export function colourwayKey(name: string) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-");
}
`,
);

console.log(`rendered ${made} squares across ${Object.keys(manifest).length} houses`);
for (const [h, rows] of Object.entries(manifest))
  console.log(`  ${h}: ${Object.keys(rows).length} colourways`);
