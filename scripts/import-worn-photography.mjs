/**
 * Bring each frame's MODEL photography in from the showcase, and write the
 * manifest the buy page reads.
 *
 * ---- Where the mapping comes from ----
 *
 * The showcase (arianoir-showcase.pages.dev) lists every frame in its
 * Eyewear section, colourway by colourway, with the photographs filed
 * under each one. That filing is the authority: a photograph is shown on a
 * buy page only if the showcase files it under that house AND that
 * colourway. Of those, only the ones with a model in them are taken; the
 * product stills already reach the page by the colourway import.
 *
 * The showcase's general album (ARIANOIR 210) is NOT used. It is filed by
 * shoot, not by frame, so nothing in it can be placed on one product.
 *
 * MONARCA has no model photograph filed under it, and gets none.
 *
 * ---- Output ----
 *
 *   public/images/worn/<slug>-<colourway>-N.webp   1200px long side, q80
 *   src/lib/worn.generated.ts                      per slug, in order
 *
 *   node scripts/import-worn-photography.mjs [--dry]
 */
import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const BASE = "https://arianoir-showcase.pages.dev/shop/img/";
const OUT = path.join("public", "images", "worn");
const MANIFEST = path.join("src", "lib", "worn.generated.ts");

/* slug → [colourway as this build names it, showcase file]. The showcase
   calls MATRIARCA's third acetate "Black"; the catalogue calls it
   "Black Wood". */
const PICKS = {
  "arca-i": [
    ["K Black", "aria-noir-arca-i-k-black-01.png"],
    ["K Black", "aria-noir-arca-i-k-black-02.png"],
    ["Z White", "5704AE8C-E8A0-4B11-B532-10682BF2CB4B-square.jpg"],
    ["Z White", "DBC05ECC-049A-4216-B18E-F24E2502A089-square.jpg"],
    ["Proceso Brown", "IMG-4700.png"],
    ["309 Blue", "IMG-4685.png"],
    ["309 Blue", "IMG-4693-square.jpg"],
  ],
  "arca-ii": [
    ["Noir", "aria-noir-arca-ii-noir-01.png"],
    ["Dark Tortoise", "4B696DB1-E276-4C29-A305-2FFD3B3CAF7D-square.jpg"],
  ],
  ahava: [
    ["Rose", "aria-noir-ahava-rose-01.png"],
    ["Rose", "aria-noir-ahava-rose-02.png"],
    ["Rose", "aria-noir-ahava-rose-03.png"],
  ],
  matriarca: [
    ["Brown", "11ACF514-DBED-476E-977B-5D77A56E7383.png"],
    ["Black Wood", "475809EF-1B0A-4BCD-A34C-E5C15B488A0B.png"],
    ["Midnight Noir", "AD396156-0329-41CC-A898-1D72F8A1DADC-square.jpg"],
  ],
  patriarca: [
    ["Brown", "2414B572-9348-4762-A72E-BD942E396EAA-square.jpg"],
    ["Black", "40598D22-800A-48F9-92DB-453068A2724C-square.jpg"],
    ["Midnight Noir", "aria-noir-patriarca-midnight-noir-01.jpg"],
    ["Midnight Noir", "aria-noir-patriarca-midnight-noir-02.jpg"],
  ],
};

const dry = process.argv.includes("--dry");
const kebab = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

if (!dry) {
  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });
}

const out = {};
for (const [slug, rows] of Object.entries(PICKS)) {
  out[slug] = [];
  const seen = {};
  for (const [colorway, file] of rows) {
    const res = await fetch(BASE + file);
    if (!res.ok) throw new Error(`${file}: ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    const n = (seen[colorway] = (seen[colorway] ?? 0) + 1);
    const name = `${slug}-${kebab(colorway)}-${n}.webp`;
    const img = sharp(buf)
      .rotate()
      .flatten({ background: "#ffffff" })
      .resize(1200, 1200, { fit: "inside", withoutEnlargement: true });
    const { width, height } = dry
      ? (await img.toBuffer({ resolveWithObject: true })).info
      : await img.webp({ quality: 80 }).toFile(path.join(OUT, name));
    out[slug].push({ src: `/images/worn/${name}`, colorway, width, height });
    console.log(`${name}  ${width}x${height}`);
  }
}

const ts = `/* Generated by scripts/import-worn-photography.mjs. Do not edit by hand. */
export type WornPlate = { src: string; colorway: string; width: number; height: number };

export const WORN: Readonly<Record<string, readonly WornPlate[]>> = ${JSON.stringify(out, null, 2)};
`;
if (!dry) await writeFile(MANIFEST, ts);
console.log(`${Object.values(out).flat().length} plates${dry ? " (dry)" : ""}`);
