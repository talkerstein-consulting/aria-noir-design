/**
 * Read the live storefront and write src/lib/catalogue.ts.
 *
 *   node scripts/sync-catalogue.mjs
 *
 * ---- Why this exists ----
 *
 * The buy page needs three facts per colourway that this repo cannot
 * derive: the Shopify product handle, the price, and whether it is in
 * stock. All three were guessed before this script, and all three guesses
 * were wrong in ways that would have cost sales:
 *
 *   - Handles are per COLOURWAY, not per house, and they are irregular.
 *     `ahava` is Root Beer Float. `arca` is ARCA II Noir. `matriarca` is
 *     Brown. There is no rule; `/products/<slug>` 404s for every house.
 *   - Price is per colourway, not per house. AHAVA Dark Tortoise is $225
 *     against $200 for the rest of the run; MONARCA Velvet Rose is $247.50
 *     against $150. A single "from" price on the buy page would have
 *     under-quoted three frames.
 *   - MATRIARCA Black Wood is genuinely out of stock, which the catalogue
 *     copy said in prose and nothing enforced.
 *
 * Shopify publishes all of it at /products.json with no key, so the right
 * answer is to read it rather than to keep a second copy by hand. The
 * generated file is committed so a build never depends on the store being
 * up — but it is GENERATED, so fix the store and re-run, never edit it.
 *
 * Anything the store sells that is not eyewear (the alpaca sweaters) is
 * deliberately not written out. The site links to /collections/all for
 * those; it does not need to model them.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SHOP = "https://arianoir.com";
const OUT = resolve(
  fileURLToPath(new URL("../src/lib/catalogue.ts", import.meta.url)),
);

/** Store title prefix → catalogue slug. Longest first: "ARCA II" has to be
 *  tested before "ARCA I", which is a prefix of it. */
const HOUSES = [
  ["ARCA II", "arca-ii"],
  ["ARCA I", "arca-i"],
  ["AHAVA", "ahava"],
  ["MATRIARCA", "matriarca"],
  ["PATRIARCA", "patriarca"],
  ["MONARCA", "monarca"],
];

/** "CARAMEL STRIPE" → "Caramel Stripe", "309 BLUE" → "309 Blue". */
const titleCase = (s) =>
  s
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(" ");

function parse(title) {
  const t = title.trim().replace(/\s+/g, " ");
  for (const [name, slug] of HOUSES) {
    if (!t.toUpperCase().startsWith(name)) continue;
    /* Titles are inconsistent about the separator: "AHAVA - NOIR" but
       "MONARCA NOIR". Strip either. */
    const rest = t.slice(name.length).replace(/^\s*-\s*/, "").trim();
    if (!rest) continue;
    return { slug, colorway: titleCase(rest) };
  }
  return null;
}

async function main() {
  const res = await fetch(`${SHOP}/collections/all/products.json?limit=250`);
  if (!res.ok) throw new Error(`${SHOP} returned ${res.status}`);
  const { products } = await res.json();

  const byHouse = new Map();
  let skipped = 0;

  for (const p of products) {
    const parsed = parse(p.title);
    if (!parsed) {
      skipped += 1;
      continue;
    }
    const variant = p.variants?.[0];
    if (!variant) continue;

    if (!byHouse.has(parsed.slug)) byHouse.set(parsed.slug, []);
    byHouse.get(parsed.slug).push({
      colorway: parsed.colorway,
      handle: p.handle,
      /* Shopify gives price as a decimal string. Kept as a NUMBER of cents
         so nothing downstream has to parse money, and formatted once at
         the point it is shown. */
      cents: Math.round(parseFloat(variant.price) * 100),
      available: variant.available === true,
      /* The numeric variant id is what makes a headless cart possible
         without an API token: Shopify honours /cart/<variantId>:<qty> as a
         permalink straight into its own checkout. No Storefront token, no
         server, no second inventory. */
      variantId: variant.id,
    });
  }

  const houses = [...byHouse.entries()].sort();
  for (const [, list] of houses) list.sort((a, b) => a.colorway.localeCompare(b.colorway));

  const body = houses
    .map(([slug, list]) => {
      const rows = list
        .map(
          (c) =>
            `    { colorway: ${JSON.stringify(c.colorway)}, handle: ${JSON.stringify(c.handle)}, variantId: ${c.variantId}, cents: ${c.cents}, available: ${c.available} },`,
        )
        .join("\n");
      return `  ${JSON.stringify(slug)}: [\n${rows}\n  ],`;
    })
    .join("\n");

  const file = `/**
 * GENERATED by scripts/sync-catalogue.mjs — do not edit by hand.
 *
 * The live storefront's eyewear, one row per colourway: the Shopify handle
 * to link at, the price in cents, and whether it is in stock. Read from
 * ${SHOP}/collections/all/products.json, which Shopify publishes without a
 * key.
 *
 * Re-run the script when the store changes. Editing this file instead
 * creates the second catalogue the script exists to prevent.
 *
 * Last synced: ${new Date().toISOString().slice(0, 10)}
 */

export type CatalogueEntry = {
  colorway: string;
  /** Shopify product handle. Irregular — see the script's header. */
  handle: string;
  /** Numeric variant id, for /cart/<id>:<qty> checkout permalinks. */
  variantId: number;
  cents: number;
  available: boolean;
};

export const CATALOGUE: Record<string, readonly CatalogueEntry[]> = {
${body}
};
`;

  writeFileSync(OUT, file);
  const total = houses.reduce((n, [, l]) => n + l.length, 0);
  console.log(
    `${total} colourways across ${houses.length} houses → src/lib/catalogue.ts`,
  );
  console.log(`${skipped} non-eyewear products skipped (they live on /collections/all).`);
}

main();
